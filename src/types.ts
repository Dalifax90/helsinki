export const WIDTH = 960;
export const HEIGHT = 576;
export const TILE = 32;
export type Point = { x: number; y: number };
export type Rect = Point & { width: number; height: number; hazard?: boolean };
export type Character = Point & { facing: number; moving: boolean };
export type Player = Character & { lives: number; maxLives: number; invulnerable: number; cooldown: number; meleeCooldown: number; dashTime: number; dashCooldown: number; dashDirection: Point };
export type Enemy = Character & { cooldown: number; variant: number; hp: number; maxHp: number; flash: number; slow: number };
export type Bullet = Point & { vx: number; vy: number; owner: 'player' | 'enemy'; life: number };
export type Particle = Point & { vx: number; vy: number; life: number; color: string };
export type Smoke = Point & { life: number };
export type ItemKind = 'spread' | 'rapid' | 'shield' | 'heart' | 'frost' | 'blade' | 'vitality';
export type Item = Point & { kind: ItemKind };
export type Inventory = { spread: number; rapid: number; shields: number; frost: number; blade: number; vitality: number; novaCooldown: number };
export type Nova = Point & { life: number };
export type Slash = Point & { angle: number; radius: number; life: number };
export type BossState = 'arrival' | 'volley' | 'telegraph' | 'dash' | 'recover';
export type Boss = Point & { hp: number; maxHp: number; state: BossState; timer: number;
  shotTimer: number; volleys: number; target: Point; direction: Point; enraged: boolean; flash: number };
export type Input = { x: number; y: number; fire: boolean; melee: boolean; dash: boolean; power: boolean; aim: Point | null };
export const emptyInput = (): Input => ({ x: 0, y: 0, fire: false, melee: false, dash: false, power: false, aim: null });
